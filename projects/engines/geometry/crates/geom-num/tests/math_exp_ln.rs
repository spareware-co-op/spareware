#[path = "math_reference.rs"]
mod reference;

use geom_num::math::{exp, ln};
use geom_num::{NumError, Real};
use reference::{Owed, Rng, assert_owed, owed};

/// The outcome of a call of a public maths function, to compare with what it owes.
fn outcome(r: Result<Real, NumError>) -> Owed {
    match r {
        Ok(v) => Owed::Value(v.get()),
        Err(NumError::NotFinite) => Owed::NotFinite,
        Err(NumError::OutsideDomain) => Owed::OutsideDomain,
        Err(e) => panic!("a maths function returned {e:?}"),
    }
}

#[track_caller]
fn check_exp(x: f64) {
    assert_owed(
        outcome(exp(x)),
        owed(&[x], reference::exp(x)),
        &format!("exp({x:e} = {:#018x})", x.to_bits()),
    );
}

#[track_caller]
fn check_ln(x: f64) {
    assert_owed(
        outcome(ln(x)),
        owed(&[x], reference::ln(x)),
        &format!("ln({x:e} = {:#018x})", x.to_bits()),
    );
}

/// `2^k` for `−1074 ≤ k ≤ 1023`, exactly.
fn pow2(k: i32) -> f64 {
    if k >= -1022 {
        f64::from_bits(((k + 1023) as u64) << 52)
    } else {
        f64::from_bits(1u64 << (k + 1074))
    }
}

#[test]
fn exp_worst_cases() {
    for &b in &EXP_WORST {
        check_exp(f64::from_bits(b));
    }
}

#[test]
fn ln_worst_cases() {
    for &b in &LN_WORST {
        let x = f64::from_bits(b);
        if x > 0.0 {
            check_ln(x);
        }
    }
}

#[test]
fn exp_random_arguments() {
    let mut rng = Rng(0xe4_0001);
    for _ in 0..1500 {
        // The whole finite range of interest, uniformly.
        check_exp(rng.uniform(-746.0, 710.0));
        // Small arguments, every binade down to the 1 + x path.
        check_exp(rng.log_uniform(-60, 0));
        // Every bit pattern (most give 1, +0 or +∞, which must be exact too).
        check_exp(rng.any_finite());
    }
    for _ in 0..800 {
        // Subnormal results and the boundary of the subnormal path.
        check_exp(rng.uniform(-745.2, -707.0));
        // Near overflow.
        check_exp(rng.uniform(700.0, 709.8));
    }
}

#[test]
fn ln_random_arguments() {
    let mut rng = Rng(0x10_0001);
    for _ in 0..2000 {
        // Every positive binade, subnormals included.
        let x = rng.any_finite().abs();
        if x > 0.0 {
            check_ln(x);
        }
        // Near 1, where the result is small and the table entries are 1.
        check_ln(1.0 + rng.uniform(-0.01, 0.01));
        check_ln(1.0 + rng.log_uniform(-60, -10));
        // Near √2, where the reduction switches.
        check_ln(rng.uniform(1.40, 1.43) * 2f64.powi((rng.next_u64() % 64) as i32 - 32));
        // Subnormals.
        let sub = f64::from_bits(rng.next_u64() >> 12);
        if sub > 0.0 {
            check_ln(sub);
        }
    }
}

/// Just below 1, `x ∈ [1 − 2^−8, 1)`, the accurate path evaluates a Taylor series instead of
/// CORE-MATH's polynomial, which was fitted for the other sign of its argument (see the module
/// documentation of `geom_num::math`'s logarithm). Dense coverage of that interval, with extra
/// weight near `1 − 2^−8`, where the replaced polynomial was least accurate, and near 1.
#[test]
fn ln_just_below_one() {
    let mut rng = Rng(0x10_0002);
    let lo = 1.0 - 2f64.powi(-8);
    for _ in 0..4000 {
        check_ln(rng.uniform(lo, 1.0));
        check_ln(lo + rng.uniform(0.0, 2f64.powi(-16)));
        check_ln(1.0 - rng.log_uniform(-53, -9).abs());
    }
    for k in 1..=2000u64 {
        check_ln(f64::from_bits(1f64.to_bits() - k)); // 1 − k·2^−53
        check_ln(f64::from_bits(lo.to_bits() + k));
        check_ln(f64::from_bits(lo.to_bits() - k));
    }
}

#[test]
fn thresholds_and_special_values() {
    let around = |x: f64| {
        [
            x.next_down().next_down(),
            x.next_down(),
            x,
            x.next_up(),
            x.next_up().next_up(),
        ]
    };
    for t in [
        // 2^−54: below it, e^x rounds to 1
        f64::from_bits(0x3c90_0000_0000_0000),
        -f64::from_bits(0x3c90_0000_0000_0000),
        // the overflow threshold
        f64::from_bits(0x4086_2e42_fefa_39f0),
        -f64::from_bits(0x4086_2e42_fefa_39f0),
        // the underflow threshold
        -f64::from_bits(0x4087_4910_d52d_3052),
        // the start of the subnormal path
        -f64::from_bits(0x4086_232b_dd7a_bcd2),
        // e^x near 2^−1075, 2^−1022 and the largest double
        -745.133_219_101_941_1,
        -708.396_418_532_264_1,
        709.782_712_893_384,
        0.0,
        1.0,
        -1.0,
    ] {
        for x in around(t) {
            check_exp(x);
        }
    }
    assert_owed(outcome(exp(0.0)), Owed::Value(1.0), "exp(+0)");
    assert_owed(outcome(exp(-0.0)), Owed::Value(1.0), "exp(−0)");
    assert_owed(outcome(exp(f64::INFINITY)), Owed::NotFinite, "exp(+∞)");
    assert_owed(outcome(exp(f64::NEG_INFINITY)), Owed::NotFinite, "exp(−∞)");
    assert_owed(outcome(exp(1000.0)), Owed::NotFinite, "overflow");
    assert_owed(outcome(exp(-1000.0)), Owed::Value(0.0), "underflow");
    assert_owed(outcome(exp(-746.0)), Owed::Value(0.0), "underflow to +0");
    assert_owed(outcome(exp(1.0)), Owed::Value(core::f64::consts::E), "e");

    assert_owed(outcome(ln(1.0)), Owed::Value(0.0), "ln(1)");
    assert_owed(outcome(ln(0.0)), Owed::NotFinite, "ln(+0), a pole");
    assert_owed(outcome(ln(-0.0)), Owed::NotFinite, "ln(−0), a pole");
    assert_owed(outcome(ln(f64::INFINITY)), Owed::NotFinite, "ln(+∞)");
    assert_owed(
        outcome(ln(2.0)),
        Owed::Value(core::f64::consts::LN_2),
        "ln(2)",
    );
    assert_owed(
        outcome(ln(10.0)),
        Owed::Value(core::f64::consts::LN_10),
        "ln(10)",
    );
    for x in [
        1.0,
        2.0,
        0.5,
        f64::MIN_POSITIVE,
        f64::from_bits(1),
        f64::MAX,
        core::f64::consts::SQRT_2,
    ] {
        for y in around(x) {
            if y > 0.0 {
                check_ln(y);
            }
        }
    }
    // Outside the domain, refused as such; not finite, refused first. Never a NaN (chapter 21).
    for x in [-1.0, -f64::MIN_POSITIVE, -f64::from_bits(1), f64::MIN] {
        assert_eq!(ln(x), Err(NumError::OutsideDomain), "ln({x})");
    }
    for x in [f64::NEG_INFINITY, f64::NAN, -f64::NAN] {
        assert_eq!(ln(x), Err(NumError::NotFinite), "ln({x})");
        assert_eq!(exp(x), Err(NumError::NotFinite), "exp({x})");
    }
    // Every power of two: ln(2^k) = k·ln 2 correctly rounded.
    for k in -1074..=1023 {
        check_ln(pow2(k));
    }
}

