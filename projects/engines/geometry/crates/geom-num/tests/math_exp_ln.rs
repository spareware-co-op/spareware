//! `geom_num::math::{exp, ln}` are correctly rounded: every result is compared, bit for bit, with
//! the correctly rounded value from the rigorous big-number reference in `math_reference.rs`.
//!
//! Inputs: CORE-MATH's hard-to-round cases (a sample of every section of `exp.wc` and `log.wc`),
//! thousands of random arguments over every binade and over the ranges of each code path, the
//! overflow, underflow and subnormal thresholds, and every special value.
//!
//! The functions return a `Real` or an error (the module documentation of `geom_num::math`): each
//! call is checked against what it owes, `reference::owed`, from the reference's IEEE 754 value,
//! so an overflow or a pole is `NotFinite` and a negative logarithm `OutsideDomain`.

