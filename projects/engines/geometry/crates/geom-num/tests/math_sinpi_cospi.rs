#[path = "math_reference.rs"]
mod reference;

use geom_num::math::{cospi, sinpi};
use geom_num::{NumError, Real};
use reference::{Owed, Rng, assert_owed, owed};

/// The outcome of a call of a public maths function, to compare with what it owes.
fn outcome(r: Result<Real, NumError>) -> Owed {
    match r {
        Ok(v) => Owed::Value(v.get()),
        Err(NumError::NotFinite) => Owed::NotFinite,
        Err(NumError::OutsideDomain) => Owed::OutsideDomain,
        Err(e) => panic!("a maths function returned {e:?}"),
    }
}

/// `sinpi(x)` against the reference, whose zero has IEEE 754-2019's sign; the public function's
/// zero is +0, which adding +0 to the reference's value gives (and changes nothing else).
#[track_caller]
fn check_sinpi(x: f64) {
    assert_owed(
        outcome(sinpi(x)),
        owed(&[x], reference::sinpi(x) + 0.0),
        &format!("sinpi({x:e} = {:#018x})", x.to_bits()),
    );
}

/// `cospi(x)` against the reference, a zero as +0 as for [`check_sinpi`].
#[track_caller]
fn check_cospi(x: f64) {
    assert_owed(
        outcome(cospi(x)),
        owed(&[x], reference::cospi(x) + 0.0),
        &format!("cospi({x:e} = {:#018x})", x.to_bits()),
    );
}

#[test]
fn sinpi_worst_cases() {
    for &b in &SINPI_WORST {
        let x = f64::from_bits(b);
        check_sinpi(x);
        check_sinpi(-x);
    }
}

#[test]
