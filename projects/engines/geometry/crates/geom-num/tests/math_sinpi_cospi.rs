//! `geom_num::math::{sinpi, cospi}` are correctly rounded: every result is compared, bit for bit,
//! with the correctly rounded value from the rigorous big-number reference in
//! `math_reference.rs`.
//!
//! Inputs: CORE-MATH's hard-to-round cases (a sample of every section of `sinpi.wc` and
//! `cospi.wc`, both signs), thousands of random arguments over every binade and over the ranges
//! of each code path, every special value, and the quarter turns, where the result must be
//! exactly 0 or ±1, a zero always +0 (the crate's one-zero rule; the port underneath keeps IEEE
//! 754-2019 §9.2.1's signs, which `math.rs`'s unit tests check).
//!
//! The functions return a `Real` or an error (the module documentation of `geom_num::math`): each
//! call is checked against what it owes, `reference::owed`, from the reference's IEEE 754 value.

