//! The corpus register and its fetcher: every outside collection of models the tests run over, with
//! its source, version, SHA-256, licence, and whether we may store it (chapter 28.12; piece G114).
//!
//! What it does: [`Manifest::parse`] reads the register (`corpora/manifest.json`, [`MANIFEST_PATH`])
//! into typed records and checks the rules below. [`tree_digest`] gives a folder's one digest.
//! [`fetch`] brings a corpus into a cache, from its pinned source, unmodified, and refuses it unless
//! its digest is the register's. [`check_vendored`] holds the corpora folder itself to the register.
//! The binary `corpus` lists the register, checks it in CI (`-- check`), fetches (`-- fetch`) and
//! prints the digest a new entry needs (`-- digest`).
//!
//! The rules, from 28.12, 29.15, 29.20 and decision 32.11 (rule (i)):
//!
//! - **Every corpus says all of it.** Source, version, licence, what it is for; a digest for what is
//!   stored or fetched; a `decision` naming who decides what for one not used.
//! - **Nothing non-commercial, anywhere**: "non-commercial data cannot sit in a co-op's public CI"
//!   (32.11), so an entry under such a licence may only be `not-used`.
//! - **No licence, no copy.** Stored data must be under a licence on [`STORABLE`], or the kernel's
//!   own. Copyleft data is fetched and never stored (32.6). `CC-BY-ND-4.0` is stored or fetched only
//!   unmodified, which a digest pins.
//! - **Credits.** Every stored corpus carries its credit, unless its licence asks for none (CC0).
//! - **Vendored files match.** Every file under the corpora folder belongs to a stored corpus, sits
//!   in its folder, and the folder's digest is the register's. A file nothing lists fails, so an
//!   unlicensed file cannot slip in beside a licensed one.
//! - **Unmodified.** A fetched corpus's digest is checked before anything reads it, and a mismatch
//!   deletes what was fetched.
//!
//! Guarantees:
//!
//! - **Nothing ambiguous parses**: unknown fields, a missing field, a malformed id or digest, or two
//!   entries with one id are each a [`CorpusError`].
//! - **One digest per tree**: [`tree_digest`] depends only on each file's path and bytes, in byte
//!   order of path, never on a machine, a clock or an archive's layout.
//! - **A hash-checked fetch or none.**
//!
//! Method: chapters 28.12 and 29.15, rule (i) of decision 32.11
//! (`projects/engines/geometry/architecture/`). A folder's digest is SHA-256 over one line per file,
//! `<sha256> <size> <path>\n`, as `sha256sum` lists a tree. Downloads run `curl` and `git` as
//! programs, with their standard flags; the register adds no network code of its own.
//!
//! Cost: linear in the register to parse; [`tree_digest`] reads every byte of the tree; [`fetch`]
//! costs the download.

