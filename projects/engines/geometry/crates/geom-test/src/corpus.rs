/// The register's path, relative to the workspace root, one component per entry.
pub const MANIFEST_PATH: [&str; 7] = [
    "projects",
    "engines",
    "geometry",
    "crates",
    "geom-test",
    "corpora",
    "manifest.json",
];

/// The register's text as this crate was built with it.
pub const EMBEDDED: &str = include_str!("../corpora/manifest.json");

/// The register format this reader reads.
pub const FORMAT: u32 = 1;

/// The licences stored data may carry, besides the permissive ones (`licence::PERMISSIVE`): the
/// public-domain dedication, the attribution licences, and the Eclipse Distribution Licence (a BSD
/// licence) under rule (i) of 32.11. `CC-BY-ND-4.0` is here because a digest keeps a copy unmodified.
pub const STORABLE: [&str; 5] = ["CC0-1.0", "CC-BY-4.0", "CC-BY-ND-4.0", "EDL-1.0", "MPL-2.0"];

/// Licences that ask for no credit.
pub const NO_CREDIT: [&str; 1] = ["CC0-1.0"];

/// What we do with a corpus.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Storage {
    /// A copy may live in the repository, under `corpora/<id>/`.
    Stored,
    /// Fetched at test time, unmodified, checked against its digest.
    Fetched,
    /// Rebuilt in our own files from its descriptions: nothing is copied.
    Rebuilt,
    /// Generated by our own code.
    Generated,
    /// Not used until the decision it names is made.
    NotUsed,
}

/// Where a corpus's bytes come from.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case", deny_unknown_fields)]
pub enum Fetch {
    /// Paths of a Git repository at a pinned commit.
    Git {
        /// The repository.
        url: String,
        /// The commit, 40 hexadecimal digits.
        commit: String,
        /// The paths taken from it.
        paths: Vec<String>,
    },
    /// Named files, each with its own hash.
    Files(Vec<FetchFile>),
}

/// One file to download.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FetchFile {
    /// Its URL.
    pub url: String,
    /// The name it is kept under.
    pub name: String,
    /// Its SHA-256.
    pub sha256: Hash,
}

/// One corpus.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Corpus {
    /// Its id: lowercase letters, digits and hyphens, and its folder's name.
    pub id: String,
    /// What it is.
    pub what: String,
    /// What the tests use it for.
    pub used_for: String,
    /// Where it comes from.
    pub source: String,
    /// The version pinned: a commit, a release or a date of access.
    pub version: String,
    /// Its licence: an SPDX expression, or `LicenseRef-<name>` where SPDX has none.
    pub licence: String,
    /// What we do with it.
    pub storage: Storage,
    /// The digest of what is stored or fetched ([`tree_digest`]).
    pub sha256: Option<Hash>,
    /// The credit a stored copy carries.
    pub credit: Option<String>,
    /// Where its bytes come from.
    pub fetch: Option<Fetch>,
    /// For a corpus not used: who decides what, and where that is recorded.
    pub decision: Option<String>,
}

/// The register.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    /// The register format, [`FORMAT`].
    pub format: u32,
    /// What the file is, for a person reading it.
    pub about: String,
    /// Every corpus.
    pub corpora: Vec<Corpus>,
}

/// Why the register cannot be read, or which rule it breaks.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CorpusError {
    /// The text is not the register's JSON shape (serde's message).
    Json(String),
    /// A register of another format.
    Format(u32),
    /// A rule is broken.
    Rule {
        /// The corpus.
        id: String,
        /// The rule.
        what: String,
    },
}

impl fmt::Display for CorpusError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CorpusError::Json(e) => write!(f, "not the corpus register: {e}"),
            CorpusError::Format(n) => write!(f, "register format {n}, this reader reads {FORMAT}"),
            CorpusError::Rule { id, what } => write!(f, "corpus {id}: {what}"),
        }
    }
}

impl core::error::Error for CorpusError {}

/// Whether `licence` says the data may not be used commercially.
fn is_non_commercial(licence: &str) -> bool {
    let upper = licence.to_ascii_uppercase();
    upper.contains("-NC") || upper.contains("NONCOMMERCIAL") || upper.contains("NON-COMMERCIAL")
}

/// Every licence named in `expression`: the identifiers between its operators.
fn identifiers(expression: &str) -> Vec<&str> {
    expression
        .split(|c: char| c.is_whitespace() || c == '(' || c == ')')
        .filter(|word| !word.is_empty() && !matches!(*word, "AND" | "OR" | "WITH"))
        .collect()
}

/// Whether data under `licence` may be stored: one way to comply uses only storable licences. The
/// grammar is `licence::Expr`'s; an expression it refuses cannot be stored.
fn is_storable(licence: &str) -> bool {
    if identifiers(licence).len() == 1 {
        return STORABLE.contains(&licence) || Expr::parse(licence).is_ok_and(|e| e.permissive());
    }
    // A choice is stored under its first storable branch, and a licence with AND must hold in full.
    licence
        .split(" OR ")
        .any(|branch| {
            identifiers(branch)
                .iter()
                .all(|one| STORABLE.contains(one) || Expr::parse(one).is_ok_and(|e| e.permissive()))
        })
}

/// Whether a credit may be left out: every licence of `licence` asks for none.
fn asks_no_credit(licence: &str) -> bool {
    identifiers(licence).iter().all(|one| NO_CREDIT.contains(one))
}

fn is_label(text: &str) -> bool {
    !text.is_empty()
        && text
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

impl Corpus {
    fn rules(&self) -> Result<(), String> {
        if !is_label(&self.id) {
            return Err("the id must be lowercase letters, digits and hyphens".to_owned());
        }
        for (name, text) in [
            ("what", &self.what),
            ("used_for", &self.used_for),
            ("source", &self.source),
            ("version", &self.version),
            ("licence", &self.licence),
        ] {
            if text.trim().is_empty() {
                return Err(format!("{name} is empty"));
            }
        }
        let needs_bytes = matches!(self.storage, Storage::Stored | Storage::Fetched);
        if needs_bytes && (self.sha256.is_none() || self.fetch.is_none()) {
            return Err("stored and fetched corpora need a digest and a pinned source".to_owned());
        }
        if !needs_bytes && (self.sha256.is_some() || self.fetch.is_some()) {
            return Err("only a stored or fetched corpus has bytes to pin".to_owned());
        }
        if (self.storage == Storage::NotUsed) != self.decision.is_some() {
            return Err("a corpus not used, and only one, names its decision".to_owned());
        }
        if is_non_commercial(&self.licence) && self.storage != Storage::NotUsed {
            return Err(format!(
                "{} is non-commercial, which cannot sit in a public CI (32.11)",
                self.licence
            ));
        }
        if self.storage == Storage::Stored {
            if !is_storable(&self.licence) {
                return Err(format!("{} data cannot be stored", self.licence));
            }
            if self.credit.is_none() && !asks_no_credit(&self.licence) {
                return Err(format!("{} asks for a credit, and none is given", self.licence));
            }
        }
        if let Some(Fetch::Git { commit, paths, .. }) = &self.fetch {
            if commit.len() != 40 || !commit.bytes().all(|b| b.is_ascii_hexdigit()) {
                return Err("a Git source pins a full commit".to_owned());
            }
            if paths.is_empty() {
                return Err("a Git source names its paths".to_owned());
            }
        }
        if matches!(&self.fetch, Some(Fetch::Files(files)) if files.is_empty()) {
            return Err("a list of files names at least one".to_owned());
        }
        Ok(())
    }
}

impl Manifest {
    /// Reads the register and checks every rule of the module header it can see alone.
    ///
    /// # Errors
    ///
    /// [`CorpusError`], at the first thing that does not hold.
    pub fn parse(text: &str) -> Result<Manifest, CorpusError> {
        let manifest: Manifest =
            serde_json::from_str(text).map_err(|e| CorpusError::Json(e.to_string()))?;
        if manifest.format != FORMAT {
            return Err(CorpusError::Format(manifest.format));
        }
        let mut seen = BTreeSet::new();
        for corpus in &manifest.corpora {
            corpus.rules().map_err(|what| CorpusError::Rule {
                id: corpus.id.clone(),
                what,
            })?;
            if !seen.insert(corpus.id.as_str()) {
                return Err(CorpusError::Rule {
                    id: corpus.id.clone(),
                    what: "two entries with one id".to_owned(),
                });
            }
        }
        Ok(manifest)
    }

    /// The register compiled into this crate.
    ///
    /// # Errors
    ///
    /// As [`Manifest::parse`].
    pub fn embedded() -> Result<Manifest, CorpusError> {
        Manifest::parse(EMBEDDED)
    }

    /// The corpus `id`.
    #[must_use]
    pub fn get(&self, id: &str) -> Option<&Corpus> {
        self.corpora.iter().find(|c| c.id == id)
    }
}

/// Every file under `dir`, as `(path with '/', full path)`, in byte order of path.
fn files_under(dir: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    fn walk(dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) -> Result<(), String> {
        let entries = fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        for entry in entries {
            let entry = entry.map_err(|e| format!("{}: {e}", dir.display()))?;
            let name = entry.file_name().to_string_lossy().into_owned();
            let path = entry.path();
            if path.is_dir() {
                walk(&path, &format!("{prefix}{name}/"), out)?;
            } else {
                out.push((format!("{prefix}{name}"), path));
            }
        }
        Ok(())
    }
    let mut out = Vec::new();
    walk(dir, "", &mut out)?;
    out.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    Ok(out)
}

/// The digest of a tree given as `(path, bytes)`, in byte order of path: SHA-256 over one line per
/// file, `<sha256> <size> <path>\n`.
#[must_use]
pub fn digest_of(files: &[(String, Vec<u8>)]) -> Hash {
    let mut sorted: Vec<&(String, Vec<u8>)> = files.iter().collect();
    sorted.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    let mut sha = Sha256::new();
    for (path, bytes) in sorted {
        let line = format!("{} {} {path}\n", Digest(sha256(bytes)), bytes.len());
        sha.write(line.as_bytes());
    }
    Hash(sha.finish())
}

/// The digest of every file under `dir`, the same on every machine.
///
/// # Errors
///
/// A file that cannot be read.
pub fn tree_digest(dir: &Path) -> Result<Hash, String> {
    let mut files = Vec::new();
    for (path, full) in files_under(dir)? {
        let bytes = fs::read(&full).map_err(|e| format!("{}: {e}", full.display()))?;
        files.push((path, bytes));
    }
    Ok(digest_of(&files))
}

/// Runs a program, and says how it failed.
fn program(name: &str, args: &[&str], dir: Option<&Path>) -> Result<(), String> {
    let mut command = Command::new(name);
    command.args(args);
    if let Some(dir) = dir {
        command.current_dir(dir);
    }
    let out = command.output().map_err(|e| format!("{name}: {e}"))?;
    if out.status.success() {
        Ok(())
    } else {
        Err(format!(
            "{name} {}: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

/// Brings the bytes of `corpus` into `into`, with nothing checked.
fn download(corpus: &Corpus, into: &Path) -> Result<(), String> {
    fs::create_dir_all(into).map_err(|e| format!("{}: {e}", into.display()))?;
    match &corpus.fetch {
        None => Err(format!("{} has no source to fetch from", corpus.id)),
        Some(Fetch::Files(files)) => {
            for file in files {
                let path = into.join(&file.name);
                let text = path.to_string_lossy().into_owned();
                program(
                    "curl",
                    &["--fail", "--location", "--silent", "--show-error", "--retry", "3", "--output", &text, &file.url],
                    None,
                )?;
                let bytes = fs::read(&path).map_err(|e| format!("{text}: {e}"))?;
                if sha256(&bytes) != file.sha256.0 {
                    return Err(format!("{}: its SHA-256 is not the register's", file.url));
                }
            }
            Ok(())
        }
        Some(Fetch::Git { url, commit, paths }) => {
            let git = |args: &[&str]| program("git", args, Some(into));
            git(&["init", "--quiet"])?;
            git(&["remote", "add", "origin", url])?;
            git(&["fetch", "--quiet", "--depth", "1", "origin", commit])?;
            let mut checkout = vec!["checkout", "--quiet", "FETCH_HEAD", "--"];
            checkout.extend(paths.iter().map(String::as_str));
            git(&checkout)?;
            fs::remove_dir_all(into.join(".git")).map_err(|e| format!("{}: {e}", into.display()))
        }
    }
}

/// What a fetch did.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Fetched {
    /// The cache already held it, and its digest is the register's.
    Cached,
    /// It was downloaded, and its digest is the register's.
    Downloaded,
}

/// Brings `corpus` into `cache/<id>`, unmodified. A copy already there is kept if its digest is the
/// register's; anything else is replaced. A download whose digest is not the register's is deleted.
///
/// # Errors
///
/// A download that fails, or bytes that are not the register's.
pub fn fetch(corpus: &Corpus, cache: &Path) -> Result<Fetched, String> {
    let dir = cache.join(&corpus.id);
    let want = corpus
        .sha256
        .ok_or_else(|| format!("{} has no digest to check", corpus.id))?;
    if dir.is_dir() {
        if tree_digest(&dir)? == want {
            return Ok(Fetched::Cached);
        }
        fs::remove_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    let result = download(corpus, &dir).and_then(|()| tree_digest(&dir));
    match result {
        Ok(got) if got == want => Ok(Fetched::Downloaded),
        Ok(got) => {
            fs::remove_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            Err(format!(
                "{}: its digest is {}, the register's {}",
                corpus.id,
                String::from(got),
                String::from(want)
            ))
        }
        Err(e) => {
            if dir.is_dir() {
                fs::remove_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            }
            Err(e)
        }
    }
}

/// The digest of `corpus`'s pinned source, for a new or changed entry: downloads it into `scratch`.
///
/// # Errors
///
/// A download that fails.
pub fn digest_source(corpus: &Corpus, scratch: &Path) -> Result<Hash, String> {
    let dir = scratch.join(&corpus.id);
    if dir.is_dir() {
        fs::remove_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    download(corpus, &dir)?;
    tree_digest(&dir)
}

/// Every breach of the register under the corpora folder `dir`: a file outside a stored corpus's
/// folder, or a folder whose digest is not the register's. The manifest and README are the folder's
/// own.
///
/// # Errors
///
/// A file that cannot be read.
pub fn check_vendored(manifest: &Manifest, dir: &Path) -> Result<Vec<String>, String> {
    let mut problems = Vec::new();
    let mut folders = BTreeSet::new();
    for (path, _) in files_under(dir)? {
        match path.split_once('/') {
            None if matches!(path.as_str(), "manifest.json" | "README.md") => {}
            None => problems.push(format!("{path}: no corpus lists this file")),
            Some((folder, _)) => {
                folders.insert(folder.to_owned());
            }
        }
    }
    for folder in folders {
        match manifest.get(&folder) {
            None => problems.push(format!("{folder}/: no corpus lists this folder")),
            Some(corpus) if corpus.storage != Storage::Stored => problems.push(format!(
                "{folder}/: this corpus may not be stored ({:?})",
                corpus.storage
            )),
            Some(corpus) => {
                let got = tree_digest(&dir.join(&folder))?;
                if Some(got) != corpus.sha256 {
                    problems.push(format!(
                        "{folder}/: its digest is {}, not the register's",
                        String::from(got)
                    ));
                }
            }
        }
    }
    Ok(problems)
}
