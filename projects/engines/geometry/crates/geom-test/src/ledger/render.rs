//! The text of `PROVENANCE.md` and `NOTICE`, written from the map's sources, the licence texts and
//! the method notes.
//!
//! What it does: [`provenance`] writes the ledger as Markdown tables, one per class of chapter
//! 29.1 the code takes (PORT, PORT METHOD, DEPEND), and one of the method notes; [`notice`] writes
//! the notices as plain text: each ported source with its ported files, the origin files and
//! copyright lines each header copies, any further credit and the licence text in full; then the
//! credits of every source consulted; then the published crates.
//!
//! Guarantees:
//!
//! - **Deterministic text.** Sections and rows are written in a fixed order (ported sources by
//!   name, credits by name then link, uses by file, notes by path), with `\n` line ends and one
//!   final newline, from nothing but the inputs.
//! - **Valid tables.** A table cell never holds a line break or an unescaped `|`: line breaks
//!   become spaces and `|` is written `\|`, as GitHub Flavored Markdown's table extension asks.
//! - **Nothing dropped.** Every source of the map is written, with every file that uses it; a
//!   ported source with no licence text is still listed in `NOTICE`, with a line saying its text
//!   is missing (the check fails on it, [`crate::ledger::notices::match_ports`]).
//!
//! Method: tables as GitHub Flavored Markdown 0.29's table extension defines them
//! (<https://github.github.com/gfm/#tables-extension->); the notice layout of the hand-kept file
//! G05 wrote, which it replaces, and chapter 29.20, rule 4
//! (`projects/engines/geometry/architecture/29-sources-licences.md`).
//!
//! Cost: linear in the size of the output.

use core::fmt::Write as _;
use std::collections::BTreeMap;

use crate::ledger::methods::{self, Note};
use crate::ledger::notices::Port;
use crate::ledger::{NOTICES_DIR, Source, WRITE_COMMAND, origins, repository_and_commit};
use crate::map::classes;
use crate::map::json::Value;

