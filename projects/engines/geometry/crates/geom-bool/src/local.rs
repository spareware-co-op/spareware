//! The arrangement step of local operations, and the topology changes it makes (13.1, 13.14).
//!
//! What it does: a local operation is a geometry step followed by one arrangement step (13.1).
//! [`local_step`] is that step: it takes the operation's target, the new faces its geometry step
//! made as tool operands extended past their final size, and the selection to keep. It arranges
//! them once, as a boolean does, and returns the body with its history. That history records every
//! [`TopologyChange`] the step made, and refuses any change its [`AllowSet`] does not hold, as
//! `TopologyChangeNotAllowed`.
//!
//! - **The full path** ([`Plan::Arrange`]) runs `combine`'s arrangement, selection, canonical
//!   rebuild, names and checker.
//! - **The fast path** ([`Plan::Glued`]) is for a plan that has proven its operands lie outside each
//!   other but on whole faces two of them share, facing opposite ways: an extrusion of a valid
//!   region, a revolve clear of its axis. It skips the arrangement and gives each polygon its own
//!   piece, with the winding numbers the proof fixes. Then it runs the same selection, canonical
//!   rebuild, names and checker, so the two paths give the same body. A shared face that is not a
//!   whole face of both, or two operands on one plane facing one way, is refused, never arranged
//!   instead. The diagnostics record the skip.
//!
//! The changes are read from the arrangement's pieces of each input face and from the result's
//! history:
//!
//! - **Face added:** an output face generated by a tool.
//! - **Faces merge:** an output face merged from two or more inputs.
//! - **Loop changes:** an input face split into two or more output faces. Also an output face
//!   carried on unchanged or modified from an input face with fewer loops than it had, a hole
//!   closed.
//! - **Body splits:** more solid lumps in the result than in the target.
//! - **Clash trimmed:** input faces some of whose pieces are kept and some buried, lying with the
//!   side they face inside another operand's material.
//! - **Overshoot removed:** target faces whose every piece is buried.
//! - **Face vanishes:** a target face whose every piece is dropped with none buried and none shared:
//!   collapsed. A face that turns inside out is the geometry step's to find and report, since its
//!   pieces arrive the right way round.
//! - **Self-overlap cut:** never on a flat body, whose faces are planar and cannot cross
//!   themselves; the curved arrangement decides it, from a face's self-intersection (G176).
//! - **Vertex split:** a target vertex of four or more faces deleted, where two or more new vertices
//!   lie on at least two faces descended from its faces and otherwise only on faces the step
//!   generated, joined by the new edges between them.
//!
//! A face shared by a tool and the target, facing opposite ways, is replaced and is no change: the
//! geometry step's new face takes its place.
//!
//! Guarantees:
//!
//! - **One arrangement, or a proven skip.** The fast path runs only on the plan's proof that the
//!   operands meet on whole shared faces. What it builds then goes through the full path's own
//!   selection, rebuild, names and checker, so a valid plan gives the same body either way.
//! - **Every change recorded, none unallowed.** The history holds each change found, in name
//!   order, and a change outside the call's set is an error naming its class and entities.
//! - **Exact on flat bodies.** Every fate is a winding number of the exact arrangement, or a name
//!   in the history; nothing is measured.
//!
//! Method: chapter 13.1's five steps and fast path and 13.14's taxonomy
//! (`projects/engines/geometry/architecture/13-sweeps-blends-offsets.md`), on chapter 11's
//! arrangement and its names (`projects/engines/geometry/architecture/11-booleans.md`).
//!
//! Cost: the boolean's, or on the fast path the selection's alone. Classifying is linear in the
//! pieces and the history's records, and quadratic only in a deleted vertex's faces. The fast path
//! matches shared faces in O(p²) over the polygons. Recursion: none.

