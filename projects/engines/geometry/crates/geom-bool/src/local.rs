/// How the arrangement step runs (13.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Plan {
    /// Arrange the operands.
    Arrange,
    /// The plan has proven that the operands lie outside each other, but on whole faces two of
    /// them share facing opposite ways: build the pieces directly.
    Glued,
}

/// Which path ran.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Path {
    /// The arrangement.
    Arranged,
    /// The plan's proof, the arrangement skipped.
    Fast,
}

/// A local operation's arrangement step.
#[derive(Clone, Debug)]
pub struct LocalInput<'b> {
    /// The body the operation changes, with its names.
    pub target: Operand<'b>,
    /// The geometry step's new faces, as operands extended past their final size.
    pub tools: Vec<Operand<'b>>,
    /// What to keep.
    pub select: Selection,
    /// What merges.
    pub merge: Merge,
    /// The least exact result taken.
    pub accept: Option<Exactness>,
    /// The changes the operation may make, narrowed by its caller.
    pub may: AllowSet,
    /// How it runs.
    pub plan: Plan,
}

/// What a local operation's arrangement step gives.
#[derive(Clone, Debug, PartialEq)]
pub struct Local {
    /// The body.
    pub body: Body,
    /// How its entities relate to the operands', with every topology change it made.
    pub history: History,
    /// The names the step made (as `Combined::names`).
    pub names: Vec<TopoName>,
    /// Which path ran.
    pub path: Path,
}

/// The arrangement step of a local operation (module documentation).
///
/// # Errors
///
/// An [`OpError`]: the boolean's, for operands that cannot enter or a result the checker refuses;
/// `InvalidOperand` for a target without names, or for a fast path whose operands share a plane
/// in a way the proof does not allow; `TopologyChangeNotAllowed` for a change outside `may`.
pub fn local_step(
    ctx: &OpContext<'_>,
    exec: &Exec<'_>,
    input: &LocalInput<'_>,
) -> Result<OpOutput<Local>, OpError> {
    let mut operands = Vec::with_capacity(input.tools.len().saturating_add(1));
    operands.push(input.target);
    operands.extend(input.tools.iter().copied());
    let boolean = BooleanInput {
        operands,
        select: alloc::vec![input.select.clone()],
        merge: input.merge,
        accept: input.accept,
    };
    let mut meter = ctx.meter();
    let ready = prepare(&boolean, &mut meter).map_err(|e| prepared(ctx, e, &meter))?;
    let (classified, exactness, path) = match input.plan {
        Plan::Arrange => {
            let (c, e) = arranged_input(ctx, exec, &boolean, &ready, &mut meter)?;
            (c, e, Path::Arranged)
        }
        Plan::Glued => {
            let e = operands_exactness(ctx, &boolean)?;
            let c = glued(&ready).ok_or_else(|| fail(ctx, CombineDetail::InvalidOperand))?;
            (c, e, Path::Fast)
        }
    };
    let out = selected(ctx, &boolean, &ready, &classified, exactness, &mut meter)?;
    let mut diagnostics = out.diagnostics;
    let Some(combined) = out
        .result
        .into_iter()
        .next()
        .and_then(|l| l.into_iter().next())
    else {
        return Err(fail(ctx, CombineDetail::ResultInvalid));
    };
    let Combined {
        body,
        history,
        names,
        ..
    } = combined;
    let Some(history) = history else {
        return Err(fail(ctx, CombineDetail::InvalidOperand));
    };
    let test = ready
        .tests
        .first()
        .ok_or_else(|| fail(ctx, CombineDetail::BadSelection))?;
    let scene = Inputs {
        ready: &ready,
        operands: &boolean.operands,
        target: input.target.key,
    };
    let changes = scene
        .changes(&classified, test, &history, &body)
        .ok_or_else(|| fail(ctx, CombineDetail::ResultInvalid))?;
    if let Err((detail, change)) = allowed(&changes, input.may) {
        return Err(OpError::new(ctx.path().clone(), detail).with_entities(named_in(change)));
    }
    let history = History::new(
        history.records().iter().cloned(),
        history.deleted().clone(),
        changes,
    )
    .map_err(|_| fail(ctx, CombineDetail::ResultInvalid))?;
    if path == Path::Fast {
        diagnostics.extend(Diagnostic::new(
            "bool.arrangement_skipped",
            "the plan proves the operands meet only on whole shared faces, so the pieces were \
             built directly",
        ));
    }
    let mut result = OpOutput::new(
        Local {
            body,
            history,
            names,
            path,
        },
        exactness,
    );
    result.diagnostics = diagnostics;
    Ok(result)
}

/// The names a change involves, for its error.
fn named_in(change: &TopologyChange) -> Vec<NameId> {
    match change {
        TopologyChange::VertexSplit { vertex, edges } => core::iter::once(*vertex)
            .chain(edges.names().iter().copied())
            .collect(),
        TopologyChange::FaceVanished { face, .. }
        | TopologyChange::FaceAdded { face, .. }
        | TopologyChange::LoopChanged { face, .. } => alloc::vec![*face],
        TopologyChange::SelfOverlapCut { face, along } => core::iter::once(*face)
            .chain(along.names().iter().copied())
            .collect(),
        TopologyChange::ClashTrimmed { faces } | TopologyChange::OvershootRemoved { faces } => {
            faces.names().to_vec()
        }
        TopologyChange::FacesMerged { faces, into } => faces
            .names()
            .iter()
            .copied()
            .chain(core::iter::once(*into))
            .collect(),
        TopologyChange::BodySplit { lumps } => lumps.names().to_vec(),
    }
}

/// How two planes lie, compared in canonical form, so a plane and a multiple of it are one.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Relation {
    /// Different planes.
    Apart,
    /// One plane, facing one way.
    Same,
    /// One plane, facing opposite ways.
    Opposite,
}

/// How `p` and `q` lie; `None` past the coefficients' width, which a plane within budget never
/// reaches.
fn relation(p: &Plane, q: &Plane) -> Option<Relation> {
    let (a, b) = (canonical(p).ok()?, canonical(q).ok()?);
    Some(if a.plane != b.plane {
        Relation::Apart
    } else if a.flipped == b.flipped {
        Relation::Same
    } else {
        Relation::Opposite
    })
}

/// Whether two lists of planes hold the same planes, each facing the same way.
fn same_planes(a: &[Plane], b: &[Plane]) -> bool {
    let within = |x: &[Plane], y: &[Plane]| {
        x.iter()
            .all(|p| y.iter().any(|q| relation(p, q) == Some(Relation::Same)))
    };
    // A piece's bounds are distinct planes, so two lists of one length, one within the other, are
    // the same list.
    a.len() == b.len() && within(a, b)
}

/// The fast path's pieces (module documentation): each polygon whole, outside every operand in
/// front and inside its own behind, but where another operand's polygon is the same piece facing
/// the other way, which lies in front of it. Faces of two operands on one plane facing one way lie
/// side by side, as an extrusion's sides lie by its base's, which the plan's proof says. `None`
/// where two operands' faces face each other on one plane but are not one piece, or an operand
/// is no solid.
fn glued(ready: &Prepared) -> Option<Vec<Classified>> {
    let owner = |i: usize| ready.owners.get(i).copied();
    let mut out = Vec::with_capacity(ready.polygons.len());
    for (i, p) in ready.polygons.iter().enumerate() {
        let entry = p.entry?;
        let mut partner = None;
        for (j, q) in ready.polygons.iter().enumerate() {
            if owner(j) == owner(i) || relation(&q.piece.face, &p.piece.face)? != Relation::Opposite
            {
                continue;
            }
            if !same_planes(&q.piece.bounds, &p.piece.bounds) {
                return None;
            }
            if partner.is_some() {
                return None;
            }
            partner = Some((j, q.entry?));
        }
        let mut front = Winding::new();
        let mut back = Winding::new();
        back.add(entry, 1).ok()?;
        if let Some((_, other)) = partner {
            front.add(other, 1).ok()?;
        }
        out.push(Classified {
            polygon: i,
            piece: p.piece.clone(),
            front,
            back,
            first: partner.is_none_or(|(j, _)| j > i),
        });
    }
    Some(out)
}

/// What happened to an input face's pieces.
#[derive(Clone, Copy, Debug, Default)]
struct Fate {
    /// Pieces kept.
    kept: u32,
    /// Pieces dropped with the side they face inside another operand's material, not shared.
    buried: u32,
    /// Pieces dropped where another operand's face is the same plane facing the other way.
    shared: u32,
}

/// The operands of a step, for reading names.
struct Inputs<'a> {
    /// The prepared operands.
    ready: &'a Prepared,
    /// The operands.
    operands: &'a [Operand<'a>],
    /// The target's key.
    target: crate::operand::OperandKey,
}

/// A name as an id.
fn id(key: geom_topo::order::NameKey) -> NameId {
    NameId::from_bytes(key.0)
}

impl Inputs<'_> {
    /// The operand that polygon `i` belongs to.
    fn operand_of(&self, i: usize) -> Option<&Operand<'_>> {
        let place = *self.ready.owners.get(i)?;
        let (key, _) = self.ready.keys.get(place)?;
        self.operands.iter().find(|o| o.key == *key)
    }

    /// The name of the face polygon `i` comes from, and whether it is the target's.
    fn face_of(&self, i: usize) -> Option<(NameId, bool)> {
        let operand = self.operand_of(i)?;
        let row = usize::try_from(*self.ready.rows.get(i)?).ok()?;
        let key = *operand.body.names()?.faces.get(row)?;
        Some((id(key), operand.key == self.target))
    }

    /// Each input face's fate, by name, with whether it is the target's.
    fn fates(
        &self,
        classified: &[Classified],
        test: &WindingTest,
    ) -> BTreeMap<NameId, (Fate, bool)> {
        let mut fates: BTreeMap<NameId, (Fate, bool)> = BTreeMap::new();
        for c in classified.iter().filter(|c| c.first) {
            let Some((named, mine)) = self.face_of(c.polygon) else {
                continue;
            };
            let own = self.ready.polygons.get(c.polygon).and_then(|p| p.entry);
            let fate = &mut fates.entry(named).or_insert((Fate::default(), mine)).0;
            if test.holds(&c.front) != test.holds(&c.back) {
                fate.kept = fate.kept.saturating_add(1);
                continue;
            }
            let shared = self.ready.polygons.iter().enumerate().any(|(j, q)| {
                self.ready.owners.get(j) != self.ready.owners.get(c.polygon)
                    && relation(&c.piece.face, &q.piece.face) == Some(Relation::Opposite)
            });
            let buried = c
                .front
                .pairs()
                .iter()
                // A winding keeps a pair only while its count is not zero.
                .any(|(entry, _)| Some(*entry) != own);
            if shared {
                fate.shared = fate.shared.saturating_add(1);
            } else if buried {
                fate.buried = fate.buried.saturating_add(1);
            }
        }
        fates
    }

    /// The target's body.
    fn target_body(&self) -> Option<&Body> {
        self.operands
            .iter()
            .find(|o| o.key == self.target)
            .map(|o| o.body)
    }

    /// Every change the step made (module documentation), in the order a history keeps; `None`
    /// where a body's rows or names cannot be read.
    fn changes(
        &self,
        classified: &[Classified],
        test: &WindingTest,
        history: &History,
        body: &Body,
    ) -> Option<Vec<TopologyChange>> {
        let mut out = Vec::new();
        let target = self.target_body()?;
        let outn = body.names()?;
        let out_faces: BTreeSet<NameId> = outn.faces.iter().map(|k| id(*k)).collect();
        let out_vertices: BTreeSet<NameId> = outn.vertices.iter().map(|k| id(*k)).collect();
        let origin: BTreeMap<NameId, &Origin> = history
            .records()
            .iter()
            .map(|r| (r.output, &r.origin))
            .collect();
        // A tool's face that comes through whole keeps its own name, as in any boolean; to the
        // target it is a new face, in the role a boolean gives a tool's faces.
        let mut tool_faces: BTreeMap<NameId, crate::operand::OperandKey> = BTreeMap::new();
        for o in self.operands.iter().filter(|o| o.key != self.target) {
            for k in &o.body.names()?.faces {
                tool_faces.insert(id(*k), o.key);
            }
        }
        // From the history: added and merged faces, split faces and closed holes.
        let mut splits: BTreeMap<NameId, Vec<&Record>> = BTreeMap::new();
        for r in history.records() {
            if !out_faces.contains(&r.output) {
                continue;
            }
            match &r.origin {
                Origin::Generated { role, .. } => out.push(TopologyChange::FaceAdded {
                    face: r.output,
                    role: role.clone(),
                }),
                Origin::Merged { of } => out.push(TopologyChange::FacesMerged {
                    faces: of.clone(),
                    into: r.output,
                }),
                Origin::Split { of, .. } => splits.entry(*of).or_default().push(r),
                Origin::Unchanged | Origin::Modified { .. } => {
                    if let Some(key) = tool_faces.get(&r.output) {
                        out.push(TopologyChange::FaceAdded {
                            face: r.output,
                            role: crate::names::keyed_role("tool", *key).ok()?,
                        });
                    }
                }
            }
        }
        // The step's own faces: those it added, the tools' among them.
        let own: BTreeSet<NameId> = out
            .iter()
            .filter_map(|c| match c {
                TopologyChange::FaceAdded { face, .. } => Some(*face),
                _ => None,
            })
            .collect();
        for (of, pieces) in &splits {
            if pieces.len() >= 2 {
                out.push(TopologyChange::LoopChanged {
                    face: *of,
                    change: LoopChange::FaceSplit,
                });
            }
        }
        out.extend(closed_holes(target, body, history)?);
        out.extend(self.piece_changes(classified, test)?);
        // From the bodies: lumps and split vertices.
        let (before, after) = (lumps(target)?, lumps(body)?);
        if after > before {
            let regions = solid_regions(body)?;
            out.push(TopologyChange::BodySplit {
                lumps: NameList::new(regions),
            });
        }
        out.extend(split_vertices(target, body, &origin, &own, &out_vertices)?);
        Some(out)
    }

    /// The changes the pieces show: trimmed, removed and vanished faces.
    fn piece_changes(
        &self,
        classified: &[Classified],
        test: &WindingTest,
    ) -> Option<Vec<TopologyChange>> {
        let mut out = Vec::new();
        let mut trimmed = Vec::new();
        let mut overshoot = Vec::new();
        for (face, (fate, mine)) in self.fates(classified, test) {
            let gone = fate.kept == 0;
            if !gone && fate.buried > 0 {
                trimmed.push(face);
            } else if gone && mine && fate.buried > 0 {
                overshoot.push(face);
            } else if gone && mine && fate.shared == 0 {
                out.push(TopologyChange::FaceVanished {
                    face,
                    why: Vanish::Collapsed,
                });
            }
        }
        if !trimmed.is_empty() {
            out.push(TopologyChange::ClashTrimmed {
                faces: NameSet::new(trimmed).ok()?,
            });
        }
        if !overshoot.is_empty() {
            out.push(TopologyChange::OvershootRemoved {
                faces: NameSet::new(overshoot).ok()?,
            });
        }
        Some(out)
    }
}

/// The target's faces that came through with fewer loops than they had: a hole closed.
fn closed_holes(target: &Body, body: &Body, history: &History) -> Option<Vec<TopologyChange>> {
    let (inn, outn) = (target.names()?, body.names()?);
    // The face each input became: itself, under its own name (a one-to-one change keeps it,
    // 20.2), or the one it merged into.
    let mut became: BTreeMap<NameId, NameId> =
        outn.faces.iter().map(|k| (id(*k), id(*k))).collect();
    for r in history.records() {
        if let Origin::Merged { of } = &r.origin {
            for input in of.names() {
                became.entry(*input).or_insert(r.output);
            }
        }
    }
    let mut out = Vec::new();
    for (row, key) in inn.faces.iter().enumerate() {
        let name = id(*key);
        let Some(&now) = became.get(&name) else {
            continue;
        };
        let after = outn.faces.iter().position(|k| id(*k) == now)?;
        if loops(body, after)? < loops(target, row)? {
            out.push(TopologyChange::LoopChanged {
                face: name,
                change: LoopChange::HoleClosed,
            });
        }
    }
    Some(out)
}

/// Target vertices of four or more faces that the step deleted, each with the new edges that
/// join the two or more new vertices on its faces' descendants and the step's own faces.
fn split_vertices(
    target: &Body,
    body: &Body,
    origin: &BTreeMap<NameId, &Origin>,
    own: &BTreeSet<NameId>,
    out_vertices: &BTreeSet<NameId>,
) -> Option<Vec<TopologyChange>> {
    let (inn, outn) = (target.names()?, body.names()?);
    let mut out = Vec::new();
    for (row, key) in inn.vertices.iter().enumerate() {
        let vertex = id(*key);
        if out_vertices.contains(&vertex) {
            continue;
        }
        let around: BTreeSet<NameId> = faces_at(target, row)?
            .into_iter()
            .filter_map(|f| inn.faces.get(f).map(|k| id(*k)))
            .collect();
        if around.len() < 4 {
            continue;
        }
        // Every face around a deleted vertex changed, so each has a record saying from what.
        let descends = |face: NameId| {
            origin.get(&face).is_some_and(|o| match o {
                Origin::Modified { from } | Origin::Merged { of: from } => {
                    from.names().iter().any(|f| around.contains(f))
                }
                Origin::Split { of, .. } => around.contains(of),
                Origin::Unchanged | Origin::Generated { .. } => false,
            })
        };
        let mut new = BTreeSet::new();
        for (at, key) in outn.vertices.iter().enumerate() {
            let name = id(*key);
            if !matches!(origin.get(&name), Some(Origin::Generated { .. })) {
                continue;
            }
            let faces = faces_at(body, at)?;
            let names: Vec<NameId> = faces
                .iter()
                .map(|f| outn.faces.get(*f).map(|k| id(*k)))
                .collect::<Option<_>>()?;
            let from_v = names.iter().filter(|f| descends(**f)).count();
            if from_v >= 2 && names.iter().all(|f| descends(*f) || own.contains(f)) {
                new.insert(at);
            }
        }
        // It became several only if new edges join them.
        let mut edges = Vec::new();
        let a = body.arenas();
        for e in (0..a.rows(Arena::Edge)).filter_map(Ix::<geom_topo::Edge>::new) {
            let ends = (
                a.edges.start.get(e).copied().flatten(),
                a.edges.end.get(e).copied().flatten(),
            );
            if let (Some(s), Some(t)) = ends
                && new.contains(&s.to_usize())
                && new.contains(&t.to_usize())
            {
                edges.push(id(*outn.edges.get(e.to_usize())?));
            }
        }
        if edges.is_empty() {
            continue;
        }
        out.push(TopologyChange::VertexSplit {
            vertex,
            edges: NameList::new(edges),
        });
    }
    Some(out)
}

/// The loops of face `row`.
fn loops(body: &Body, row: usize) -> Option<u32> {
    let a = body.arenas();
    let f = Ix::<Face>::new(u32::try_from(row).ok()?)?;
    let mut n = 0u32;
    let mut at: Option<Ix<Loop>> = a.faces.first_loop.get(f).copied().flatten();
    for _ in 0..=a.rows(Arena::Loop) {
        let Some(l) = at else { return Some(n) };
        n = n.saturating_add(1);
        at = a.loops.next.get(l).copied().flatten();
    }
    None
}

/// The rows of the faces around vertex `row`.
fn faces_at(body: &Body, row: usize) -> Option<Vec<usize>> {
    let a = body.arenas();
    let mut out = BTreeSet::new();
    for n in (0..a.rows(Arena::Fin)).filter_map(Ix::<geom_topo::Fin>::new) {
        let e = *a.fins.edge.get(n)?;
        let ends = [
            a.edges.start.get(e).copied().flatten(),
            a.edges.end.get(e).copied().flatten(),
        ];
        if ends
            .iter()
            .flatten()
            .any(|v: &Ix<Vertex>| v.to_usize() == row)
        {
            out.insert(a.loops.face.get(*a.fins.loop_.get(n)?)?.to_usize());
        }
    }
    Some(out.into_iter().collect())
}

/// The outer shells of a body's solid regions: its lumps.
fn lumps(body: &Body) -> Option<usize> {
    let a = body.arenas();
    let mut n = 0usize;
    for r in (0..a.rows(Arena::Region)).filter_map(Ix::<geom_topo::Region>::new) {
        if *a.regions.kind.get(r)? != RegionKind::Solid {
            continue;
        }
        let mut at = a.regions.first_shell.get(r).copied().flatten();
        for _ in 0..=a.rows(Arena::Shell) {
            let Some(s) = at else { break };
            n = n.saturating_add(1);
            at = a.shells.next.get(s).copied().flatten();
        }
    }
    Some(n)
}

/// The names of a body's solid regions.
fn solid_regions(body: &Body) -> Option<Vec<NameId>> {
    let a = body.arenas();
    let names = body.names()?;
    let mut out = Vec::new();
    for r in (0..a.rows(Arena::Region)).filter_map(Ix::<geom_topo::Region>::new) {
        if *a.regions.kind.get(r)? == RegionKind::Solid {
            out.push(id(*names.regions.get(r.to_usize())?));
        }
    }
    Some(out)
}
